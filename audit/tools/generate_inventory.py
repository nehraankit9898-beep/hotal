#!/usr/bin/env python3
"""Reproducible inventory generator for the 2026 StayLoop audit.

Writes:
  audit/ROUTE_INVENTORY.md        — every App Router API handler, method, auth, permission, tenant scope
  audit/ROLE_PERMISSION_MATRIX.md — role -> permission table, extracted from src/lib/permissions.ts

Usage: python3 audit/tools/generate_inventory.py   (run from repo root)
No secrets are read or printed. Static analysis only; results are heuristics that
must be confirmed by reading the handler (see audit/ROUTE_INVENTORY.md notes).
"""
import os, re, subprocess, json, tempfile, shutil, pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
API = ROOT / "src/app/api"
METHODS = ["GET", "POST", "PUT", "PATCH", "DELETE"]

def classify(src: str, rel: str) -> str:
    if "requireSuperAdminSession" in src: return "SESSION+SUPER_ADMIN"
    if "requireAuth" in src: return "SESSION (requireAuth)"
    if re.search(r"verifyWebhookSignature|x-razorpay-signature|createHmac|verifyGatewaySignature|timingSafeEqual", src):
        return "SIGNATURE / SECRET (public)"
    if "requireApiKey" in src or "authenticateApiKey" in src or "x-api-key" in src.lower():
        return "API KEY"
    return "PUBLIC (no session check in file)"

rows = []
for path in sorted(API.rglob("route.ts")):
    src = path.read_text(encoding="utf8")
    rel = "/" + str(path.parent.relative_to(API)).replace("\\", "/")
    rel = "/api" + ("" if rel == "/." else rel)
    methods = sorted(set(re.findall(r"export\s+(?:async\s+)?function\s+(GET|POST|PUT|PATCH|DELETE)\b", src)), key=METHODS.index)
    perms = sorted(set(re.findall(r'requirePermission\([^,]+,\s*"([A-Z_]+)"', src)))
    tenant = "hotelId" in src
    rows.append((rel, ",".join(methods) or "-", classify(src, rel), ", ".join(perms) or "-", "yes" if tenant else "no", str(path.relative_to(ROOT))))

with open(ROOT / "audit/ROUTE_INVENTORY.md", "w", encoding="utf8") as f:
    f.write("# Route Inventory (generated)\n\n")
    f.write("Generated by `audit/tools/generate_inventory.py` from static source analysis of ")
    f.write(f"**{len(rows)} route files** under `src/app/api`.\n\n")
    f.write("Columns: route · exported methods · auth mechanism detected in the file · permissions checked (`requirePermission`) · tenant scoping referenced (`hotelId`) · source file.\n\n")
    f.write("**Caveats.** `PUBLIC (no session check in file)` is a heuristic: a route can delegate auth to a helper "
            "or be a deliberately public endpoint (menu, pay link, feedback). Each such route was checked manually where "
            "it appears in SECURITY_FINDINGS.md. `hotelId` presence does not prove every query is scoped; "
            "scoping was verified by reading the handlers flagged in the audit.\n\n")
    f.write("| Route | Methods | Auth mechanism | Permissions checked | Tenant (`hotelId`) | Source |\n|---|---|---|---|---|---|\n")
    for r in rows:
        f.write(f"| `{r[0]}` | {r[1]} | {r[2]} | {r[3]} | {r[4]} | `{r[5]}` |\n")
    counts = {}
    for r in rows: counts[r[2]] = counts.get(r[2], 0) + 1
    f.write("\n## Summary by auth mechanism\n\n")
    for k, v in sorted(counts.items(), key=lambda kv: -kv[1]): f.write(f"- {k}: {v}\n")

# ---- role matrix: evaluate the real ROLE_PERMISSIONS table without the DB import ----
perm_src = (ROOT / "src/lib/permissions.ts").read_text(encoding="utf8")
perm_src = perm_src.replace('import { jsonError } from "@/lib/api-helpers";',
                            'const jsonError = (m: string, s: number, c: string) => ({ m, s, c });')
perm_src = re.sub(r'import type \{ AuthedUser \} from "@/lib/api-helpers";\n', "", perm_src)
tmpdir = tempfile.mkdtemp(prefix="perm-")
tmp = pathlib.Path(tmpdir) / "permissions.ts"
tmp.write_text(perm_src, encoding="utf8")
js = "import * as P from '" + str(tmp) + "'; console.log(JSON.stringify(P.ROLE_PERMISSIONS));"
out = subprocess.run(["bun", "-e", js], capture_output=True, text=True, cwd=ROOT)
shutil.rmtree(tmpdir, ignore_errors=True)
if out.returncode != 0:
    raise SystemExit("role extraction failed: " + out.stderr[-2000:])
roles = json.loads(out.stdout.strip().splitlines()[-1])
all_perms = sorted({p for ps in roles.values() for p in ps})
with open(ROOT / "audit/ROLE_PERMISSION_MATRIX.md", "w", encoding="utf8") as f:
    f.write("# Role → Permission Matrix (generated)\n\n")
    f.write("Extracted from `src/lib/permissions.ts` (`ROLE_PERMISSIONS`). Regenerate with `python3 audit/tools/generate_inventory.py`.\n\n")
    f.write(f"- Roles defined in `ROLE_PERMISSIONS`: **{len(roles)}**\n- Distinct permission identifiers: **{len(all_perms)}**\n")
    f.write("- Default-deny: `hasPermission` returns `false` for an unknown role or a permission not in the role's list (verified in source).\n")
    f.write("- **Custom roles are NOT enforced at runtime.** `resolveUserPermissions()` (src/lib/custom-roles.ts) merges custom-role grants, but it is only called to check what a caller may grant when creating roles. `requirePermission()` reads the static `ROLE_PERMISSIONS` table only, so a custom-role grant never unlocks a route. This is finding FUNC-001 in audit/FUNCTIONAL_BUGS.md. It fails closed (no escalation), but the feature does not work as documented.\n\n")
    f.write("## Per-role counts\n\n| Role | Permissions |\n|---|---|\n")
    for r, ps in roles.items(): f.write(f"| `{r}` | {len(ps)} |\n")
    f.write("\n## Full matrix (✓ = granted)\n\n")
    short = {p: p for p in all_perms}
    header = "| Permission | " + " | ".join(f"`{r}`" for r in roles) + " |\n"
    f.write(header)
    f.write("|---|" + "---|" * len(roles) + "\n")
    for p in all_perms:
        f.write(f"| `{p}` | " + " | ".join("✓" if p in roles[r] else "" for r in roles) + " |\n")
print(f"routes={len(rows)} roles={len(roles)} permissions={len(all_perms)}")
